def gen_testCaseParams(testParamsFile, currPrm):
    """Write test case parameters to idat.c file.

    Args:
        testParamsFile (file object): File object for idat.c
        currPrm (dict): Test case parameters

    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    width = currPrm["width"]
    height = currPrm["height"]
    strideInElements = currPrm["strideInElements"]
    strideOutElements = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]

    if testType != "RANDOM":
        inData = "staticRefInCase" + testId
        outData = "staticRefOutCase" + testId
    else:
        inData = "NULL"
        outData = "NULL"

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    testParamsFile.write("{\n")
    # MINVAL cases are static data too (the macro STATIC), only the data generation differs
    testParamsFile.write("%s, // Test pattern \n" % ("RANDOM" if testType == "RANDOM" else "STATIC"))
    testParamsFile.write("%s, // Input buffer\n" % ((inData)))
    testParamsFile.write("%s, // Output vector \n" % ((outData)))
    testParamsFile.write("%s, // precision \n" % (DSPLIB_utils.resolve_dType(dType)))
    testParamsFile.write("%s, // Width \n" % ((width)))
    testParamsFile.write("%s, // Height \n" % ((height)))
    testParamsFile.write("DSPLIB_CALC_STRIDE(%s * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES),// strideInElements buffer\n" % ((strideInElements), (dType)))
    testParamsFile.write("DSPLIB_CALC_STRIDE(%s * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES),// strideInElements buffer\n" % ((strideOutElements), (dType)))
    testParamsFile.write("%s, // Output data location \n" % (outputDataLocation))
    testParamsFile.write("%d, // number of reps. \n" % (int(numReps)))
    testParamsFile.write("%d, // test ID\n" % int(testId))
    testParamsFile.write("},\n")
    testParamsFile.write("#endif")
    testParamsFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the complete idat.c file from test cases.

    Args:
        idatFile (file object): Output file object for idat.c
        testCases (list): List of test case dictionaries

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "DSPLIB_absoluteValue_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] != "RANDOM":
            DSPLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static DSPLIB_absoluteValue_testParams_t testParams[] = ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert string parameters to integers in test case dictionary.

    Args:
        testCase (dict): Test case dictionary

    Returns:
        dict: Test case with numeric parameters converted to int

    """

    testCase["testId"] = int(testCase["ID"])
    testCase["width"] = int(testCase["width"])
    testCase["height"] = int(testCase["height"])
    testCase["strideInElements"] = int(testCase["strideInElements"])
    testCase["strideOutElements"] = int(testCase["strideOutElements"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case input/output data and write to C header file.

    Args:
        testCase (dict): Test case parameters

    Returns:
        list: [min_value, max_value] of output data

    """

    testId = testCase["ID"]
    width = testCase["width"]
    height = testCase["height"]
    dType = testCase["dType"]
    strideInElements = testCase["strideInElements"]
    strideOutElements = testCase["strideOutElements"]

    # Use DSPLIB_absoluteValue class to generate input and output data
    absolute_value_instance = DSPLIB_absoluteValue(
        dType=dType,
        width=width,
        height=height,
        strideInElements=strideInElements,
        strideOutElements=strideOutElements,
        testType=testCase["testType"],
        numReps=1
    )

    # Generate input data
    inData = absolute_value_instance.generate_input_data()

    # Execute ABS operation
    outData = absolute_value_instance.exec(inData)

    headerFileName = "staticRefCase" + str(testId) + ".h"

    file_io.write_header_file(inData, outData, testCase, headerFileName)

    return [np.min(outData), np.max(outData)]


testCasesCsvFile = "test_cases_list.csv"
df = pd.read_csv(testCasesCsvFile)
num_data_rows = len(df)
testIdList = list(range(1, num_data_rows + 1))

myArgs = DSPLIB_utils.getCmdLineArgs()


def gen_test_case(testCase):
    """Generate test case data for every type except RANDOM (STATIC, MINVAL)."""
    if testCase["testType"] != "RANDOM":
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as testType is RANDOM",
        )


with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)

    for testCase in testCases:
        testCase = process_test_case(testCase)

    for testCase in testCases:
        if myArgs.allCases:
            gen_test_case(testCase)
        elif int(testCase["ID"]) in testIdList:
            gen_test_case(testCase)


idatFileName = "../../DSPLIB_absoluteValue/DSPLIB_absoluteValue_idat.c"


with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)


if platform == "linux" or platform == "linux2":
    call(["clang-format", "-style=file", "-i", idatFileName])
    call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
    call(["rm", idatFileName + "~"])  # remove backup file


print("Idat file generation completed")
