def gen_testCaseParams(idatFile, currPrm):
    """Write test case parameters to idat.c file.

    Args:
        idatFile (file object): File object for idat.c
        currPrm (dict): Test case parameters

    """

    testId = currPrm["ID"]
    dTypeIn = currPrm["dTypeIn"]
    channels = currPrm["channels"]
    length = currPrm["length"]
    strideInElements = currPrm["strideInElements"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]

    if testType != "RANDOM":
        inData = "staticRefInCase" + testId
        outData = "staticRefOutCase" + testId
        testPattern = "5"  # STATIC = 5
    else:
        inData = "NULL"
        outData = "NULL"
        testPattern = "3"  # RANDOM = 3

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    idatFile.write("   {\n")
    idatFile.write("    %s,\n" % testPattern)
    idatFile.write("    (void *) %s,                        // staticIn\n" % inData)
    idatFile.write("    (void *) %s,                       // staticOut\n" % outData)
    idatFile.write("    %s,                                      // dataType\n" % (DSPLIB_utils.resolve_dType(dTypeIn)))
    idatFile.write("    %s,                                             // width\n" % (length))
    idatFile.write("    %s,                                             // height (channels)\n" % (channels))
    idatFile.write("    %s,                                             // strideIn (bytes)\n" % (strideInElements * DSPLIB_utils.sizeof_dType(dTypeIn)))
    idatFile.write("    %s,                          // outputDataLocation\n" % (outputDataLocation))
    idatFile.write("    %d,                                                // numReps\n" % (int(numReps)))
    idatFile.write("    %d                                                 // testID\n" % int(testId))
    idatFile.write("    },\n")
    idatFile.write("#endif\n")
    idatFile.write("\n")


def gen_idat_file(idatFile, testCases):
    """Generate the complete idat.c file from test cases.

    Args:
        idatFile (file object): Output file object for idat.c
        testCases (list): List of test case dictionaries

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "DSPLIB_peakAbsoluteValue_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] != "RANDOM":
            DSPLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static DSPLIB_peakAbsoluteValue_testParams_t testParams[] = {\n")
    idatFile.write("/*\n")
    idatFile.write(" testPattern,\n")
    idatFile.write(" staticIn,\n")
    idatFile.write(" staticOut,\n")
    idatFile.write(" dataType,\n")
    idatFile.write(" width,\n")
    idatFile.write(" height,\n")
    idatFile.write(" strideIn,\n")
    idatFile.write(" outputDataLocation,\n")
    idatFile.write(" numReps,\n")
    idatFile.write(" testID\n")
    idatFile.write("*/\n")
    idatFile.write("\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert string parameters to integers in test case dictionary.

    Args:
        testCase (dict): Test case dictionary

    Returns:
        dict: Test case with numeric parameters converted to int

    """

    testCase["testId"] = int(testCase["ID"])
    testCase["channels"] = int(testCase["channels"])
    testCase["length"] = int(testCase["length"])
    testCase["strideInElements"] = int(testCase["strideInElements"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case input/output data and write to C header file.

    Args:
        testCase (dict): Test case parameters

    Returns:
        ndarray: Maximum absolute value of every channel

    """

    testId = testCase["ID"]
    channels = testCase["channels"]
    length = testCase["length"]
    dTypeIn = testCase["dTypeIn"]
    shape = (channels, length)

    # Generate input data with data-type-aware ranges
    if dTypeIn == "int8_t":
        minVal = -128
        maxVal = 127
    elif dTypeIn == "int16_t":
        minVal = -32768
        maxVal = 32767
    elif dTypeIn == "int32_t":
        minVal = -2147483648
        maxVal = 2147483647
    elif dTypeIn == "int64_t":
        minVal = np.iinfo(np.int64).min
        maxVal = np.iinfo(np.int64).max
    elif dTypeIn == "float":
        minVal = -100
        maxVal = 100
    elif dTypeIn == "double":
        minVal = -100
        maxVal = 100
    else:
        minVal = -100
        maxVal = 100

    # Create input data
    if dTypeIn == "float":
        inData = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(np.float32)
    elif dTypeIn == "double":
        inData = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(np.float64)
    elif dTypeIn == "int8_t":
        inData = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(np.int8)
    elif dTypeIn == "int16_t":
        inData = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(np.int16)
    elif dTypeIn == "int32_t":
        inData = np.random.uniform(low=minVal, high=maxVal, size=shape).astype(np.int32)
    elif dTypeIn == "int64_t":
        # uniform() cannot represent the full 64-bit range exactly
        inData = np.random.randint(low=minVal, high=maxVal, size=shape, dtype=np.int64)


    # Edge-case variants: small values everywhere, the extreme value at a known position
    testType = testCase["testType"]
    if testType in ("MAXFIRST", "MAXLAST", "MINVAL"):
        inData = np.clip(inData, -50, 50).astype(inData.dtype)
        if testType == "MAXFIRST":
            inData[:, 0] = -100
        elif testType == "MAXLAST":
            inData[:, length - 1] = -100
        else:
            # type minimum (integers only) at the first, middle and last element of every channel
            inData[:, 0] = inData[:, length // 2] = inData[:, length - 1] = np.iinfo(inData.dtype).min

    # Compute peakAbsoluteValue: one maximum absolute value per channel (row). Integers saturate: |minimum| = maximum, as the C7x VABS does
    if np.issubdtype(inData.dtype, np.integer):
        info = np.iinfo(inData.dtype)
        absData = np.where(inData == info.min, info.max, np.abs(inData)).astype(inData.dtype)
    else:
        absData = np.abs(inData)
    outData = np.max(absData, axis=1)

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(inData, outData, testCase, headerFileName)

    return outData

parser = argparse.ArgumentParser()
