def gen_testCaseParams(idatFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    numRows = currPrm["numRows"]
    numCols = currPrm["numCols"]
    numIndices = currPrm["numIndices"]
    strideOutElements = currPrm["strideOutElements"]
    isColSelect = currPrm["isColSelect"]
    isOutputInterleave = currPrm["isOutputInterleave"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]

    if testType == "STATIC":
        in0 = "staticRefIn0Case" + testId
        in1 = "staticRefIn1Case" + testId
        out = "staticRefOutCase" + testId
    else:
        in0 = "NULL"
        in1 = "NULL"
        out = "NULL"

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((testType)))
    idatFile.write("%s, // Index buffer\n" % ((in0)))
    idatFile.write("%s, // Table buffer\n" % ((in1)))
    idatFile.write("%s, // Output vector \n" % ((out)))
    idatFile.write("%s, // precision \n" % (DSPLIB_utils.resolve_dType(dType)))
    idatFile.write("%s, // Number of rows in the table \n" % ((numRows)))
    idatFile.write("%s, // Number of columns in the table \n" % ((numCols)))
    idatFile.write("%s, // Number of indices \n" % ((numIndices)))
    idatFile.write(
        "%s * sizeof(%s), // stride of output buffer \n"
        % ((strideOutElements), (dType))
    )
    idatFile.write("%s, // isColSelect \n" % (isColSelect))
    idatFile.write("%s, // isOutputInterleave \n" % (isOutputInterleave))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif")
    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "DSPLIB_tableSourceRowColSelector_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            DSPLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static DSPLIB_tableSourceRowColSelector_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    testCase["testId"] = int(testCase["ID"])
    testCase["numRows"] = int(testCase["numRows"])
    testCase["numCols"] = int(testCase["numCols"])
    testCase["numIndices"] = int(testCase["numIndices"])
    testCase["strideOutElements"] = int(testCase["strideOutElements"])
    testCase["isColSelect"] = int(testCase["isColSelect"])
    testCase["isOutputInterleave"] = int(testCase["isOutputInterleave"])

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out index, table, and output
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    dType = testCase["dType"]
    numRows = testCase["numRows"]
    numCols = testCase["numCols"]
    numIndices = testCase["numIndices"]
    strideOutElements = testCase["strideOutElements"]
    isColSelect = testCase["isColSelect"]
    isOutputInterleave = testCase["isOutputInterleave"]

    rng = np.random.default_rng(int(testId))

    # Indices are in range, except the first (below 0) and last (past the end) which exercise the clamp
    numSel = numCols if isColSelect == 1 else numRows
    in0 = rng.integers(0, numSel, size=numIndices).astype("int32")
    if numIndices > 2:
        in0[0] = -1
        in0[-1] = numSel + 1

    if dType == "float":
        in1 = rng.uniform(-100.0, 100.0, size=(numRows, numCols)).astype("float32")
    elif dType == "double":
        in1 = rng.uniform(-100.0, 100.0, size=(numRows, numCols)).astype("float64")
    elif dType == "int32_t":
        in1 = rng.integers(-(2**31), 2**31 - 1, size=(numRows, numCols), dtype="int64").astype("int32")
    # 64-bit values are kept within +/-2^40 so they are valid C integer literals in the idat file
    elif dType == "int64_t":
        in1 = rng.integers(-(2**40), 2**40, size=(numRows, numCols), dtype="int64")
    elif dType == "uint32_t":
        in1 = rng.integers(0, 2**32, size=(numRows, numCols), dtype="int64").astype("uint32")
    elif dType == "uint64_t":
        in1 = rng.integers(0, 2**40, size=(numRows, numCols), dtype="int64").astype("uint64")

    outRef = tableSourceRowColSelector(in0, in1, isColSelect, isOutputInterleave)
    out = np.zeros((outRef.shape[0], strideOutElements), dtype=in1.dtype)
    out[:, : outRef.shape[1]] = outRef

    headerFileName = "staticRefCase" + str(testId) + ".h"

    file_io.write_header_file(in0, in1, out, testCase, headerFileName)

    return [np.min(outRef), np.max(outRef)]


# CSV file with parameters for all test cases
testCasesCsvFile = "test_cases_list.csv"
df = pd.read_csv(testCasesCsvFile)
num_data_rows = len(df)
testIdList = []  # list of test IDs that we want to generate test data
testIdList += range(1, num_data_rows + 1)


myArgs = DSPLIB_utils.getCmdLineArgs()


def gen_test_case(testCase):
    if testCase["testType"] == "STATIC":
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as tesType is RANDOM",
        )


#############################################################################
# Open CSV file with test cases and generate header file with test data for #
# test cases of interest; based on testIdList                               #
#############################################################################

with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)

    for testCase in testCases:
        testCase = process_test_case(testCase)

    for testCase in testCases:
        if myArgs.allCases == True:
            gen_test_case(testCase)
        elif int(testCase["ID"]) in testIdList:
            gen_test_case(testCase)


idatFileName = "../../DSPLIB_tableSourceRowColSelector/DSPLIB_tableSourceRowColSelector_idat.c"


##########################################################################
# Generate idat.cpp file by parsing all the test cases in the CSV file # #
##########################################################################


with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)


if platform == "linux" or platform == "linux2":
    call(["clang-format", "-style=file", "-i", idatFileName])
    call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
    call(["rm", idatFileName + "~"])  # remove backup file


print("Idat file generation completed")
