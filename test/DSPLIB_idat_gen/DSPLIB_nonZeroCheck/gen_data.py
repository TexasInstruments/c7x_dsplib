NP_DTYPES = {
    "int8_t": np.int8,
    "uint8_t": np.uint8,
    "int16_t": np.int16,
    "uint16_t": np.uint16,
    "int32_t": np.int32,
    "uint32_t": np.uint32,
    "int64_t": np.int64,
    "uint64_t": np.uint64,
    "float": np.float32,
    "double": np.float64,
}


def gen_nonzero_values(rng, dType, shape):
    """Random non-zero values with widely varying magnitude.

    Integer values are built from random bits that are shifted both ways, so
    that elements whose low (or high) bytes are zero but which are non-zero
    overall are exercised. Floating point values span many binary orders of
    magnitude.
    """
    npType = NP_DTYPES[dType]
    if dType in ("float", "double"):
        lim = 30 if dType == "float" else 250
        mant = rng.standard_normal(shape)
        expo = rng.integers(-lim, lim + 1, size=shape).astype("float64")
        vals = (mant * np.power(10.0, expo)).astype(npType)
        vals[vals == 0] = 1.0
        return vals

    bits = np.dtype(npType).itemsize * 8
    raw = rng.integers(0, 2**64, size=shape, dtype=np.uint64)
    shr = rng.integers(0, bits, size=shape).astype(np.uint64)
    shl = rng.integers(0, bits, size=shape).astype(np.uint64)
    val = np.where(
        rng.integers(0, 2, size=shape) == 0, raw >> shr, (raw << shl)
    )
    # keep only the bits of the target width
    val = val & np.uint64(2**bits - 1)
    val[val == 0] = 1
    vals = val.astype(np.uint64).astype(npType)
    if np.issubdtype(npType, np.signedinteger):
        # avoid the most negative value, which has no portable C literal
        vals[vals == np.iinfo(npType).min] = 1
    return vals


def gen_input(dType, numSamples, numChannels, opType, axisType, seed):
    """Generate an input matrix with a controlled mix of zero / non-zero lines.

    Each reduction line (a column for axisType 0, a row for axisType 1) is
    either left in its 'trivial' state or given a single exception placed at a
    random position (first, last or anywhere):
      - ALL: lines are non-zero, some get a single zero  -> output 0
      - ANY: lines are zero, some get a single non-zero  -> output 1
    so that both output values occur and a single element decides the result.
    """
    rng = np.random.default_rng(seed)
    npType = NP_DTYPES[dType]
    shape = (numChannels, numSamples)
    isFloat = dType in ("float", "double")

    nonzero = gen_nonzero_values(rng, dType, shape)
    zeros = np.zeros(shape, dtype=npType)
    if isFloat:
        # -0.0 compares equal to zero and must be treated as zero
        negZero = rng.integers(0, 2, size=shape) == 1
        zeros[negZero] = -0.0

    numLines = numSamples if axisType == 0 else numChannels
    lineLen = numChannels if axisType == 0 else numSamples

    if opType == 0:
        in0 = nonzero.copy()
        base, exc = nonzero, zeros
    else:
        in0 = zeros.copy()
        base, exc = zeros, nonzero

    for line in range(numLines):
        if rng.integers(0, 2) == 0:
            continue
        sel = rng.integers(0, 4)
        pos = 0 if sel == 0 else (lineLen - 1 if sel == 1 else rng.integers(0, lineLen))
        if axisType == 0:
            in0[pos, line] = exc[pos, line]
        else:
            in0[line, pos] = exc[line, pos]

    return in0


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    testId = testCase["ID"]
    dType = testCase["dType"]
    numSamples = testCase["numSamples"]
    numChannels = testCase["numChannels"]
    opType = testCase["opType"]
    axisType = testCase["axisType"]

    in0 = gen_input(dType, numSamples, numChannels, opType, axisType, int(testId))

    if opType == 0:
        out = np.all(in0, axis=axisType)
    elif opType == 1:
        out = np.any(in0, axis=axisType)
    # Output data type is the same as the input data type (1 / 0, or 1.0 / 0.0)
    out = out.astype(in0.dtype)
    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


