from __future__ import print_function
from subprocess import call
from sys import platform

import sys
import numpy as np
import os
import csv

sys.path.append("../common")
import DSPLIB_utils
import file_io

KERNEL = "DSPLIB_complexMatrixMultiply"
OUTPUT_DIR = f"../../{KERNEL}"
testCasesCsvFile = "test_cases_list.csv"

inA_base = "staticRefInCaseA"
inB_base = "staticRefInCaseB"
out0_base = "staticRefOutCase"
params_base = "staticParamsCase"


def gen_testCaseParams(idatFile, currPrm):
    testId = currPrm["ID"]
    dType = currPrm["dType"]
    M = currPrm["M"]
    K = currPrm["K"]
    N = currPrm["N"]
    batch = currPrm["batch"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    numReps = currPrm["numReps"]
    outputDataLocation = currPrm["outputDataLocation"]

    if testType == "STATIC":
        inA = inA_base + testId
        inB = inB_base + testId
        out0 = f"&{out0_base}{testId}"
        params = f"&{params_base}{testId}"
    else:
        inA = "NULL"
        inB = "NULL"
        out0 = "NULL"
        params = "NULL"

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )
    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % (testType))
    idatFile.write("%s, // data type in \n" % (DSPLIB_utils.resolve_dType(dType)))
    idatFile.write("%s, // Input matrix A\n" % (inA))
    idatFile.write("%s, // Input matrix B\n" % (inB))
    idatFile.write("%s, // Parameters\n" % (params))
    idatFile.write("%s, // Output\n" % (out0))
    idatFile.write("%d, // M\n" % (M))
    idatFile.write("%d, // K\n" % (K))
    idatFile.write("%d, // N\n" % (N))
    idatFile.write("%d, // Number of batches\n" % (batch))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif")
    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    idatFile.writelines(f'#include "{KERNEL}_idat.h"')
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            DSPLIB_utils.gen_ifdefs(idatFile, testCase)
    idatFile.write(f"static {KERNEL}_testParams_t testParams[] =  ")
    idatFile.write("{\n")
    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)
    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()
    idatFile.writelines(lines)


def process_test_case(testCase):
    testCase["M"] = int(testCase["M"])
    testCase["K"] = int(testCase["K"])
    testCase["N"] = int(testCase["N"])
    testCase["batch"] = int(testCase["batch"])
    return testCase


def gen_in_data(nBatch, height, width, dType, shift=0):
    re = np.arange(nBatch * height * width).reshape([nBatch, height, width]).astype(dType)
    im = (np.arange(nBatch * height * width) + 42).reshape([nBatch, height, width]).astype(dType)
    return re + 1j * im


def genRefData(testCase):
    M = testCase["M"]
    K = testCase["K"]
    N = testCase["N"]
    nBatch = testCase["batch"]
    dType = testCase["dType"]
    shift = int(testCase["shift"])
    scaleValue = int(testCase["scaleValue"])

    params_out_string = [
        f"{shift},    // shift ",
        f"{scaleValue},    // scale value",
    ]

    if dType == "int16_t":
        np_type = np.int16
        b_shift = 4
    elif dType == "int32_t":
        np_type = np.int32
        b_shift = 10
    else:
        np_type = np.float32

    inA = gen_in_data(nBatch, M, K, np_type)
    inB = gen_in_data(nBatch, K, N, np_type, b_shift)

    # Accumulate in exact int64 arithmetic so large M/K sums don't lose
    # precision to the complex64/float32 24-bit mantissa before scaling.
    reA, imA = inA.real.astype(np.int64), inA.imag.astype(np.int64)
    reB, imB = inB.real.astype(np.int64), inB.imag.astype(np.int64)
    reC = np.zeros((nBatch, M, N), dtype=np.int64)
    imC = np.zeros((nBatch, M, N), dtype=np.int64)
    for i in range(nBatch):
        reC[i, :, :] = reA[i, :, :] @ reB[i, :, :] - imA[i, :, :] @ imB[i, :, :]
        imC[i, :, :] = reA[i, :, :] @ imB[i, :, :] + imA[i, :, :] @ reB[i, :, :]
    C = reC.astype(np.complex128) + 1j * imC.astype(np.complex128)
    C = C * scaleValue / (2**shift)
    C = file_io.saturate(np.real(C), np_type) + 1j * file_io.saturate(np.imag(C), np_type)

    testData = {"inA": inA, "inB": inB, "out0": C, "params": params_out_string}
    return testData


def gen_test_case_header_file(testCase):
    testId = testCase["ID"]
    dType = testCase["dType"]
    headerFileName = f"staticRefCase{str(testId)}.h"
    oDType = ("int32_t", "int16_t")[dType == "int16_t"]
    testData = genRefData(testCase)
    os.makedirs(f"{OUTPUT_DIR}/test_data", exist_ok=True)
    with open(os.path.join(OUTPUT_DIR, "test_data", headerFileName), "w") as f:
        file_io.write_test_data(f, testData["inA"], f"{inA_base}{testId}", dType)
        file_io.write_test_data(f, testData["inB"], f"{inB_base}{testId}", dType)
        file_io.write_params(
            f, testData["params"], f"{params_base}{testId}", f"{KERNEL}_Params"
        )
        file_io.write_test_data(f, testData["out0"], f"{out0_base}{testId}", oDType)

    return [np.min(testData["inA"]), np.max(testData["inA"])]


def gen_test_case(testCase):
    if testCase["testType"] == "STATIC":
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as testType is RANDOM",
        )


def main():
    if not os.path.exists(OUTPUT_DIR):
        os.mkdir(OUTPUT_DIR)
    testIdList = list(range(1, 1000))

    myArgs = DSPLIB_utils.getCmdLineArgs()

    np.random.seed(0)
    with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
        testCaseReader = csv.DictReader(csv_file)
        testCases = list(testCaseReader)
        for testCase in testCases:
            testCase = process_test_case(testCase)
        for testCase in testCases:
            if myArgs.allCases:
                gen_test_case(testCase)
            elif int(testCase["ID"]) in testIdList:
                gen_test_case(testCase)

    idatFileName = f"{OUTPUT_DIR}/{KERNEL}_idat.c"
    print(idatFileName)
    with open(idatFileName, "w") as idatFile:
        gen_idat_file(idatFile, testCases)
    if platform == "linux" or platform == "linux2":
        call(["clang-format", "-style=file", "-i", idatFileName])
        call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
        call(["rm", idatFileName + "~"])
    print("Idat file generation completed")


if __name__ == "__main__":
    main()
