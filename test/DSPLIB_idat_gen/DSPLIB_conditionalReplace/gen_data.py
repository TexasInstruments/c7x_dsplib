def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """
    testType = currPrm["testType"]
    dType = currPrm["dType"]
    numSamples = currPrm["numSamples"]
    numChannels = currPrm["numChannels"]
    strideIn = currPrm["strideIn"]
    strideOut = currPrm["strideOut"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    C7100 = currPrm["C7100"]
    testId = currPrm["ID"]
    enableStride = currPrm["enableStride"]

    if testType == "STATIC":
        in0 = "staticRefInCase" + testId
        cmpType = "staticRefCompareTypeCase" + testId
        constVal = "staticRefConstValueCase" + testId
        replVal = "staticRefReplaceValueCase" + testId
        out = "staticRefOutCase" + testId
    else:
        in0 = "NULL"
        cmpType = "NULL"
        constVal = "NULL"
        replVal = "NULL"
        out = "NULL"

    if C7100 == "FALSE":
        testParamsFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    testParamsFile.write("{\n")
    testParamsFile.write("%s, // testPattern \n" % ((testType)))
    testParamsFile.write("%s, // *staticIn \n" % ((in0)))
    testParamsFile.write("%s, // *staticCompareType \n" % ((cmpType)))
    testParamsFile.write("%s, // *staticConstValue \n" % ((constVal)))
    testParamsFile.write("%s, // *staticReplaceValue \n" % ((replVal)))
    testParamsFile.write("%s, // *staticOut\n" % ((out)))
    testParamsFile.write("%s, // dataType \n" % ((DSPLIB_utils.resolve_dType(dType))))
    testParamsFile.write("%s, // numSamples \n" % ((numSamples)))
    testParamsFile.write("%s, // numChannels \n" % ((numChannels)))
    if enableStride == "No":
        testParamsFile.write("%s * sizeof(%s), // strideIn \n" % ((strideIn), (dType)))
        testParamsFile.write("%s * sizeof(%s), // strideOut \n" % ((strideOut), (dType)))
    else:
        testParamsFile.write(
            "DSPLIB_CALC_STRIDE(%s * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES), // strideIn \n"
            % ((strideIn), (dType))
        )
        testParamsFile.write(
            "DSPLIB_CALC_STRIDE(%s * sizeof(%s), DSPLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
            % ((strideOut), (dType))
        )
    testParamsFile.write("%s, // Output data location \n" % (outputDataLocation))
    testParamsFile.write("%d, // number of reps. \n" % (int(numReps)))
    testParamsFile.write("%d // test ID\n" % int(testId))
    testParamsFile.write("},\n")
    testParamsFile.write("#endif\n")

    if C7100 == "FALSE":
        testParamsFile.write("#endif // if !defined(__C7100__)\n")

    testParamsFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "DSPLIB_conditionalReplace_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            DSPLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static DSPLIB_conditionalReplace_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["numSamples"] = int(testCase["numSamples"])
    testCase["numChannels"] = int(testCase["numChannels"])
    testCase["strideIn"] = int(testCase["strideIn"])
    testCase["strideOut"] = int(testCase["strideOut"])
    return testCase


NP_DTYPES = {
    "int8_t": np.int8,
    "uint8_t": np.uint8,
    "int16_t": np.int16,
    "uint16_t": np.uint16,
    "int32_t": np.int32,
    "uint32_t": np.uint32,
    "int64_t": np.int64,
    "uint64_t": np.uint64,
    "float": np.float32,
    "double": np.float64,
}

# magnitude limit of the generated floating point data, keeps values well away from overflow
FLOAT_LIMIT = {"float": 1.0e6, "double": 1.0e12}

COMPARE_TYPES = {"eq": 0, "ne": 1, "lt": 2, "le": 3, "gt": 4, "ge": 5}


def get_np_dtype(dType):
    """Return the numpy data type of a C data type string from the CSV"""
    if dType not in NP_DTYPES:
        raise ValueError("unsupported dType '%s' (use one of %s)" % (dType, ", ".join(NP_DTYPES)))
    return NP_DTYPES[dType]


def is_float(dType):
    return dType in ("float", "double")


def parse_compare_type(value):
    """Parse one compare type given as 0..5. Returns an int."""
    v = value.strip()
    if v.isdigit() and int(v) <= 5:
        return int(v)
    raise ValueError("invalid compareType '%s' (use a number 0..5)" % value)


def parse_value(value, name, dType):
    """Parse one constValue or replaceValue of the data type of the test case."""
    npType = get_np_dtype(dType)
    if is_float(dType):
        return float(value.strip())
    n = int(value.strip(), 0)
    info = np.iinfo(npType)
    if not info.min <= n <= info.max:
        raise ValueError("%s '%s' is out of %s range" % (name, value, dType))
    return n


def parse_per_channel(field, parseFn, numChannels, name, npType):
    """Parse a CSV field holding either a single value (used for all channels) or a list
    with one value per channel, e.g. "0;1;2;3;4" or "{0,1,2,3,4}" (separators: ; , or space; the
    list may be wrapped in {} or []. A list containing commas must be quoted in the CSV). Returns None if the field is blank,
    otherwise an array of type npType and length numChannels.
    """
    field = (field or "").strip()
    if field == "":
        return None
    items = [x for x in re.split(r"[;,\s]+", field.strip("{}[]() \t")) if x != ""]
    vals = [parseFn(x) for x in items]
    if len(vals) == 1:
        vals = vals * numChannels
    elif len(vals) != numChannels:
        raise ValueError(
            "%s has %d values but test case has %d channels" % (name, len(vals), numChannels)
        )
    return np.array(vals, dtype=npType)


def rand_full_range(npType, size):
    """Uniform random integers over the full range of an integer numpy type"""
    info = np.iinfo(npType)
    return np.random.randint(info.min, int(info.max) + 1, size=size, dtype=npType)


def gen_params(numChannels, testCase):
    """Generate the per-channel parameters: compareType (0..5, always int32), constValue and replaceValue
    (data type of the test case). The CSV columns compareType, constValue and replaceValue each take either one
    value (used for all channels) or ';' separated values, one per channel. Blank fields are generated randomly:
    compareType cycles through all six operators so each is exercised, constValue is in a small range so that
    equality hits, and replaceValue spans the full range of the data type.
    """
    dType = testCase["dType"]
    npType = get_np_dtype(dType)

    compareType = parse_per_channel(
        testCase.get("compareType"), parse_compare_type, numChannels, "compareType", np.int32
    )
    constValue = parse_per_channel(
        testCase.get("constValue"), lambda x: parse_value(x, "constValue", dType), numChannels, "constValue", npType
    )
    replaceValue = parse_per_channel(
        testCase.get("replaceValue"),
        lambda x: parse_value(x, "replaceValue", dType),
        numChannels,
        "replaceValue",
        npType,
    )

    if compareType is None:
        offset = int(testCase["ID"]) % 6
        compareType = ((np.arange(numChannels) + offset) % 6).astype(np.int32)
    if constValue is None:
        lo = max(-50, np.iinfo(npType).min) if not is_float(dType) else -50
        constValue = np.random.randint(lo, 51, size=numChannels).astype(npType)
    if replaceValue is None:
        if is_float(dType):
            replaceValue = np.random.uniform(-FLOAT_LIMIT[dType], FLOAT_LIMIT[dType], size=numChannels).astype(npType)
        else:
            replaceValue = rand_full_range(npType, numChannels)
    return compareType, constValue, replaceValue


def gen_input(constValue, numChannels, numSamples, dType):
    """Generate the input. About half of the samples of a channel are drawn within +-2 of the
    channel constant so that ==, <, <=, >, >= boundaries are all hit; the rest span the full range of the data
    type (floating point data is limited to +-FLOAT_LIMIT), including the extreme values for integers.
    """
    npType = get_np_dtype(dType)
    size = (numChannels, numSamples)
    offsets = np.random.randint(-2, 3, size=size)
    useNear = np.random.uniform(size=size) < 0.5

    if is_float(dType):
        full = np.random.uniform(-FLOAT_LIMIT[dType], FLOAT_LIMIT[dType], size=size).astype(npType)
        near = (constValue[:, None] + offsets).astype(npType)
        in0 = np.where(useNear, near, full).astype(npType)
        return in0

    info = np.iinfo(npType)
    full = rand_full_range(npType, size)
    # python integers avoid any wrap around of the near values at the type limits (also for 64 bit data)
    near = constValue.astype(object)[:, None] + offsets.astype(object)
    near = np.clip(near, int(info.min), int(info.max)).astype(npType)
    in0 = np.where(useNear, near, full).astype(npType)
    # sprinkle in the extremes
    extremes = np.random.uniform(size=size) < 0.02
    in0[extremes] = np.where(np.random.uniform(size=extremes.sum()) < 0.5, info.min, info.max)
    return in0


def conditional_replace(in0, compareType, constValue, replaceValue):
    """Reference model of the conditional replace. Compare types are in 0..5."""
    c = constValue[:, None]
    t = compareType[:, None]
    cond = np.zeros(in0.shape, dtype=bool)
    cond |= (t == 0) & (in0 == c)
    cond |= (t == 1) & (in0 != c)
    cond |= (t == 2) & (in0 < c)
    cond |= (t == 3) & (in0 <= c)
    cond |= (t == 4) & (in0 > c)
    cond |= (t == 5) & (in0 >= c)
    return np.where(cond, replaceValue[:, None], in0).astype(in0.dtype)


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################
    testId = testCase["ID"]
    dType = testCase["dType"]
    numSamples = testCase["numSamples"]
    numChannels = testCase["numChannels"]

    compareType, constValue, replaceValue = gen_params(numChannels, testCase)
    in0 = gen_input(constValue, numChannels, numSamples, dType)
    out = conditional_replace(in0, compareType, constValue, replaceValue)

    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, compareType, constValue, replaceValue, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


